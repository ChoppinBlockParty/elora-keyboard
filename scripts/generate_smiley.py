#!/usr/bin/env python3
"""Convert the approved 4x2 PNG sprite sheet to small RGB565-surface runs."""
from colorsys import hsv_to_rgb
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/tft_idle_smiley_sprite_sheet.png"
TARGET = ROOT / "keyboards/splitkb/halcyon/elora/keymaps/elora/smiley.c"
HEADER = ROOT / "keyboards/splitkb/halcyon/elora/keymaps/elora/smiley.h"
PREVIEW = ROOT / "assets/tft_idle_preview.gif"
SIZE = 80
DISPLAY_WIDTH, DISPLAY_HEIGHT = 135, 240
SPRITE_X, SPRITE_Y = (DISPLAY_WIDTH - SIZE) // 2, (DISPLAY_HEIGHT - SIZE) // 2
STEP_MS = 212  # 180 ms / 0.85, rounded to the nearest millisecond
PALETTE = [(255, 255, 255), (8, 8, 8), (255, 225, 0), (255, 40, 150), (35, 220, 205)]
HSV = [(0, 0, 255), (0, 0, 8), (37, 255, 255), (235, 215, 255), (124, 215, 220), (0, 0, 200)]
# (source frame, vertical movement). Four laughing frames hold the smile
# at the top of the hop; the shadow stays fixed on the ground.
STEPS = [(0, 0), (1, 2), (2, -4), (3, -10),
         (4, -14), (4, -13), (4, -12), (4, -11),
         (5, -7), (6, 1), (7, 0)]
SHADOW_START = 64


def closest(pixel):
    return min(range(len(PALETTE)), key=lambda i: sum((a-b)**2 for a,b in zip(pixel, PALETTE[i])))


image = Image.open(SOURCE).convert("RGB")
frames = []
for n in range(8):
    col, row = n % 4, n // 4
    x0, x1 = round(col * image.width / 4), round((col + 1) * image.width / 4)
    y0, y1 = round(row * image.height / 2), round((row + 1) * image.height / 2)
    tile = image.crop((x0 + 3, y0 + 3, x1 - 3, y1 - 3)).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    original = [closest(tile.getpixel((x, y))) for y in range(SIZE) for x in range(SIZE)]
    # White becomes transparent. A one-pixel pale outline keeps the original
    # black arms and rough outer contour visible against the black TFT.
    pixels = original.copy()
    for y in range(SIZE):
        for x in range(SIZE):
            if original[y * SIZE + x] == 0 and any(
                original[ny * SIZE + nx] != 0
                for ny in range(max(0, y - 1), min(SIZE, y + 2))
                for nx in range(max(0, x - 1), min(SIZE, x + 2))
            ):
                pixels[y * SIZE + x] = 5
    runs = []
    for y in range(SIZE):
        x = 0
        while x < SIZE:
            start = x
            color = pixels[y * SIZE + x]
            while x < SIZE and pixels[y * SIZE + x] == color:
                x += 1
            runs.append((start, y, x - start, color))
    frames.append(runs)

lines = [
    "// Generated from assets/tft_idle_smiley_sprite_sheet.png by scripts/generate_smiley.py",
    "// SPDX-License-Identifier: GPL-2.0-or-later",
    '#include "smiley.h"',
    "typedef struct { uint8_t x, y, width, color; } run_t;",
    "static const uint8_t colors[6][3] = {" + ", ".join("{" + ", ".join(map(str, c)) + "}" for c in HSV) + "};",
]
for n, runs in enumerate(frames):
    lines.append(f"static const run_t frame_{n}[] = {{")
    lines.extend(f"    {{{x}, {y}, {w}, {color}}}," for x, y, w, color in runs)
    lines.append("};")
lines.extend([
    "static const run_t *const frames[8] = {" + ", ".join(f"frame_{i}" for i in range(8)) + "};",
    "static const uint16_t counts[8] = {" + ", ".join(f"sizeof(frame_{i}) / sizeof(run_t)" for i in range(8)) + "};",
    "typedef struct { uint8_t frame; int8_t jump; } smiley_step_t;",
    "static const smiley_step_t steps[] = {" + ", ".join(f"{{{frame}, {jump}}}" for frame, jump in STEPS) + "};",
    "uint8_t smiley_step_count(void) { return sizeof(steps) / sizeof(steps[0]); }",
    "void draw_smiley_step(painter_device_t surface, uint8_t step, int16_t x, int16_t y) {",
    "    step %= smiley_step_count();",
    "    uint8_t frame = steps[step].frame;",
    "    for (uint16_t i = 0; i < counts[frame]; i++) {",
    "        const run_t *run = &frames[frame][i];",
    "        if (run->color == 0) continue;",
    "        const uint8_t *hsv = colors[run->color];",
    f"        int16_t row = y + run->y + (run->y < {SHADOW_START} ? steps[step].jump : 0);",
    "        qp_rect(surface, x + run->x, row, x + run->x + run->width - 1, row, hsv[0], hsv[1], hsv[2], true);",
    "    }",
    "}",
])
TARGET.write_text("\n".join(lines) + "\n")
print(f"Wrote {TARGET.relative_to(ROOT)} ({sum(map(len, frames))} runs)")
HEADER.write_text(
    "// Generated by scripts/generate_smiley.py\n"
    "#pragma once\n\n"
    '#include "hlc_tft_display/hlc_tft_display.h"\n\n'
    f"#define SMILEY_STEP_MS {STEP_MS}\n\n"
    "uint8_t smiley_step_count(void);\n"
    "void draw_smiley_step(painter_device_t surface, uint8_t step, int16_t x, int16_t y);\n"
)

# Use the generated firmware runs for the preview, on the same portrait
# 135 x 240 black display. The 3x nearest-neighbor zoom makes it readable.
display_palette = [(0, 0, 0)] + [
    tuple(round(channel * 255) for channel in hsv_to_rgb(h / 255, s / 255, v / 255))
    for h, s, v in HSV
]
gif_palette = [channel for rgb in display_palette for channel in rgb]
gif_palette += [0] * (768 - len(gif_palette))
gif_frames = []
for source_frame, jump in STEPS:
    runs = frames[source_frame]
    panel = Image.new("P", (DISPLAY_WIDTH, DISPLAY_HEIGHT), 0)
    panel.putpalette(gif_palette)
    draw = ImageDraw.Draw(panel)
    for x, y, width, color in runs:
        if color == 0:
            continue
        row = SPRITE_Y + y + (jump if y < SHADOW_START else 0)
        draw.line((SPRITE_X + x, row, SPRITE_X + x + width - 1, row), fill=color + 1)
    gif_frames.append(panel.resize((DISPLAY_WIDTH * 3, DISPLAY_HEIGHT * 3), Image.Resampling.NEAREST))
# GIF stores timing in 10 ms units; distribute rounding across the loop.
gif_durations = [round((i + 1) * STEP_MS / 10) * 10 - round(i * STEP_MS / 10) * 10 for i in range(len(STEPS))]
gif_frames[0].save(PREVIEW, save_all=True, append_images=gif_frames[1:], duration=gif_durations, loop=0, disposal=2, optimize=False)
print(f"Wrote {PREVIEW.relative_to(ROOT)} ({len(STEPS)} steps, {STEP_MS} ms per step)")
